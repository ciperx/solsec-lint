"""Renderers: machine-readable JSON and a human Markdown report."""

from __future__ import annotations

import json

BADGE = {
    "critical": "🟥 CRITICAL",
    "high": "🟧 HIGH",
    "medium": "🟨 MEDIUM",
    "low": "🟦 LOW",
    "info": "⬜ INFO",
}


def to_json(result: dict, indent: int = 2) -> str:
    return json.dumps(result, indent=indent, ensure_ascii=False)


def _esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def to_markdown(result: dict, title: str = "Solidity Security Audit") -> str:
    s = result["summary"]
    out = []
    out.append(f"# {title}")
    out.append("")
    out.append(f"**Tool:** `{result['tool']}` v{result['version']}  ")
    out.append(f"**Files scanned:** {s['files_scanned']}  ")
    sev = s["by_severity"]
    out.append("**Findings:** " + ", ".join(
        f"{BADGE[k].split()[1].title()} {sev[k]}" for k in
        ("critical", "high", "medium", "low", "info")) + f" — total **{s['findings']}**")
    out.append("")

    if s["findings"] == 0:
        out.append("✅ No findings for the enabled rule set.")
        out.append("")
        out.append("> A clean run means the patterns in `solsec/rules.py` did not match. "
                   "It is not a proof of correctness — pair static checks with tests and a manual review.")
        return "\n".join(out) + "\n"

    out.append("## Summary")
    out.append("")
    out.append("| Severity | Rule | Title | File | Line |")
    out.append("|---|---|---|---|---|")
    for fr in result["files"]:
        for f in fr["findings"]:
            out.append(f"| {BADGE[f['severity']]} | `{f['rule']}` | {_esc(f['title'])} | "
                       f"`{fr['file']}` | {f['line']} |")
    out.append("")

    out.append("## Details")
    out.append("")
    for fr in result["files"]:
        if not fr["findings"]:
            continue
        out.append(f"### `{fr['file']}`")
        out.append("")
        for i, f in enumerate(fr["findings"], 1):
            loc = f"`{fr['file']}:{f['line']}`"
            fn = f" in `{f['function']}()`" if f.get("function") else ""
            out.append(f"#### {i}. [{f['severity'].upper()}] {f['rule']} — {f['title']}")
            out.append("")
            out.append(f"- **Location:** {loc}{fn}")
            out.append(f"- **Confidence:** {f.get('confidence', 'high')}")
            out.append(f"- **Issue:** {f['message']}")
            out.append(f"- **Fix:** {f['fix']}")
            if f.get("snippet"):
                out.append("")
                out.append("```solidity")
                out.append(f["snippet"])
                out.append("```")
            out.append("")

    out.append("---")
    out.append("")
    out.append("*Generated by solsec-lint — static pattern analysis, no execution, no paid APIs.*")
    return "\n".join(out) + "\n"
